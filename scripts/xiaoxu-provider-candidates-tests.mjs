import assert from 'node:assert/strict';
import {candidateSchedule,candidateAcademic,candidateSecondClass} from '../lib/academic-provider-candidates.mjs';
const course=[{name:'工程制图',teacher:'教师甲',position:'A201',day:1,startSection:1,endSection:2,weeks:[1,3]}];
const s=candidateSchedule(course,'2026-2027-1');
assert.equal(s.verified,false);assert.equal(s.complete,false);assert.equal(s.records[0].externalId,null);
assert.throws(()=>candidateSchedule([{...course[0],weeks:[]}],'2026-1'),/课程/);
const grades=candidateAcademic('grades',[{externalId:'g1',title:'高等数学',score:'未公布',credit:4} ],{semester:'2026-2027-1'});
assert.equal(grades.records[0].score,'未公布');
assert.equal(grades.records[0].gradePoint,undefined,'Never fabricate GPA');
assert.throws(()=>candidateAcademic('grades',[{externalId:'g1',title:'A'},{externalId:'g1',title:'B'}],{semester:'2026-1'}),/duplicate/);
const exam=candidateAcademic('exams',[{externalId:'e1',title:'Python',date:'2026-12-18',location:'D202'}],{semester:'2026-2027-1'});
assert.equal(exam.records[0].startTime,undefined,'Never invent times');
assert.throws(()=>candidateAcademic('exams',[{externalId:'e2',title:'Python',date:'2026-02-30'}],{semester:'2026-1'}),/无效/);
const second=candidateSecondClass([{activityId:'a1',title:'校内活动',status:'pending',credit:2,date:'2026-11-03'}]);
