import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const ctx={Date,URL};
runInNewContext(readFileSync(new URL('../public/xiaoxu-chaoxing-cli.js',import.meta.url),'utf8'),ctx);
runInNewContext(readFileSync(new URL('../public/xiaoxu-task-import.js',import.meta.url),'utf8'),ctx);
const a=ctx.XiaoxuChaoxingCli,i=ctx.XiaoxuTaskImport;
function url(workId,enc='token-a'){return 'https://mooc1.chaoxing.com/mooc2/work/task?workId='+workId+'&courseId=456&enc='+enc;}
const hw=[{course:'高等数学',title:'实验报告',status:'未提交',deadline:'2026-11-20 23:59',url:url('123')}];
const out=a.adaptCli(hw);
assert.equal(out.sourceFormat,'hw');
assert.equal(out.batch.source,'chaoxing');
assert.equal(out.batch.tasks[0].externalId,'work:123:456');
assert.equal(out.batch.tasks[0].due,'2026-11-20');
assert.equal(out.batch.tasks[0].dueAt,'2026-11-20T23:59:00+08:00');
assert.equal(out.batch.tasks[0].status,'todo');
assert.ok(!JSON.stringify(out).includes('token-a'),'Signed URL must not be stored');
assert.equal(a.stableWorkId(url('123','token-a')),a.stableWorkId(url('123','token-b')),'URL signature changes must not alter identity');
const single={course:'高等数学',progress:{done:1,total:2},items:[{index:1,title:'实验报告',status:'待批阅',url:url('123','another-session')}]};
const fromList=a.adaptCli(single);
assert.equal(fromList.sourceFormat,'hw-ls');
assert.equal(fromList.batch.tasks[0].status,'submitted');
assert.equal(fromList.batch.tasks[0].due,'');
assert.equal(fromList.batch.tasks[0].externalId,'work:123:456');
let seq=0;const id=()=>String(++seq);const now='2026-11-02T15:30:00Z';
const initial=i.planImport([],out.batch,id,now);
assert.equal(initial.added,1);
assert.equal(initial.tasks[0].dueAt,'2026-11-20T23:59:00+08:00');
const repeat=i.planImport(initial.tasks,a.adaptCli([{...hw[0],url:url('123','rotated')}]).batch,id,now);
assert.equal(repeat.updated,0);
assert.equal(repeat.unchanged,1);
const completed=[{...initial.tasks[0],done:true,category:'高数'}];
const changed=i.planImport(completed,a.adaptCli([{...hw[0],status:'已提交',deadline:'2026-11-22 20:00'}]).batch,id,now);
assert.equal(changed.updated,1);
assert.equal(changed.tasks[0].sourceStatus,'submitted');
assert.equal(changed.tasks[0].done,true);
assert.equal(changed.tasks[0].category,'高数');
assert.equal(changed.tasks[0].dueAt,'2026-11-22T20:00:00+08:00');
const older=i.planImport(changed.tasks,fromList.batch,id,now,{preserveUnknownDue:true});
assert.equal(older.tasks[0].due,'2026-11-22','Upstream hw-ls omits DDL; do not erase known deadlines');
assert.equal(older.tasks[0].dueAt,'2026-11-22T20:00:00+08:00');
assert.equal(older.tasks[0].done,true);
assert.equal(a.adaptCli([{...hw[0],deadline:'11-20 23:59'}]).unknownDeadlines,1,'Missing year is not guessed');
assert.equal(a.adaptCli([{...hw[0],deadline:'11-20 23:59'}]).batch.tasks[0].due,'');
assert.throws(()=>a.adaptCli([]),/空列表/);
assert.throws(()=>a.adaptCli({course:'x',items:[]}),/空作业/);
assert.throws(()=>a.adaptCli([{...hw[0],url:'https://evil.chaoxing.com.attacker.net/?workId=123'}]),/可信/);
assert.throws(()=>a.adaptCli([{...hw[0],url:'http://mooc1.chaoxing.com/?workId=123'}]),/可信/);
assert.throws(()=>a.adaptCli([{...hw[0],url:'https://mooc1.chaoxing.com/?enc=abc'}]),/workId/);
assert.throws(()=>a.adaptCli([{...hw[0],url:'https://mooc1.chaoxing.com/?workId=123&workId=456'}]),/冲突/);
assert.throws(()=>a.adaptCli([{...hw[0],deadline:'2026-02-30 10:40'}]),/有效日期/);
assert.throws(()=>a.adaptCli([hw[0],hw[0]]),/重复/);
assert.throws(()=>a.adaptCli([{...hw[0],status:'未交',course:''}]),/课程/);
const safe=i.normalizeBatch(out.batch);
assert.equal(safe.tasks[0].dueAt,'2026-11-20T23:59:00+08:00');
assert.throws(()=>i.normalizeBatch({format:'xiaoxu-task-batch-v1',source:'chaoxing',
 tasks:[{...out.batch.tasks[0],due:'2026-11-21'}]}),/日期/);
console.log('校序学习通 CLI 原始 JSON 转换、稳固 ID、时间校验、签名清除、重复导入与状态分离均通过');
