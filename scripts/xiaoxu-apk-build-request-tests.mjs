import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync,mkdirSync,rmSync,readFileSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {execFileSync,spawnSync} from 'node:child_process';
const gateUrl=new URL('./xiaoxu-apk-build-request.mjs',import.meta.url);
const {apkBuildRequest,apkBuildRequested,apkFormalReleaseRequested}=await import(gateUrl);
const cwd=mkdtempSync(join(tmpdir(),'xiaoxu-build-request-'));
const git=(...args)=>execFileSync('git',args,{cwd,encoding:'utf8'}).trim();
const dir='.github/xiaoxu-apk-build-requests/pending';
const commit=()=>{git('add','-A');git('commit','-qm','synthetic');return git('rev-parse','HEAD');};
try{
 git('init','-q');git('config','user.name','synthetic');git('config','user.email','synthetic@example.invalid');
 mkdirSync(join(cwd,dir),{recursive:true});writeFileSync(join(cwd,dir,'old.txt'),'synthetic old request');
 const base=commit();
 mkdirSync(join(cwd,'docs/archive'),{recursive:true});
 git('mv',dir+'/old.txt','docs/archive/old.txt');
 const archived=commit();
 const push=(before,after)=>({ref:'refs/heads/main',before,after});
 assert.equal(apkBuildRequested('push',push(base,archived),{cwd}),false,'archive/deletion must not authorize APK packaging');
 assert.equal(apkFormalReleaseRequested('push',push(base,archived),{cwd}),false);
 mkdirSync(join(cwd,dir),{recursive:true});writeFileSync(join(cwd,dir,'new-qa.txt'),'synthetic QA request');
 const qaAdded=commit();
 assert.equal(apkBuildRequested('push',push(archived,qaAdded),{cwd}),true,'new QA request stays supported');
 assert.equal(apkFormalReleaseRequested('push',push(archived,qaAdded),{cwd}),false,'QA marker must never authorize formal release');
 writeFileSync(join(cwd,dir,'new-qa.txt'),'synthetic corrected QA request');
 const qaModified=commit();
 assert.equal(apkBuildRequested('push',push(qaAdded,qaModified),{cwd}),true,'editing QA request stays supported');
 assert.equal(apkFormalReleaseRequested('push',push(qaAdded,qaModified),{cwd}),false);
 writeFileSync(join(cwd,'unrelated.txt'),'ordinary source edit');
 const unrelated=commit();
 assert.equal(apkBuildRequested('push',push(qaModified,unrelated),{cwd}),false);
 writeFileSync(join(cwd,dir,'20261111-reviewed-final-release.txt'),'explicit formal release');
 const releaseAdded=commit();
 assert.equal(apkBuildRequested('push',push(unrelated,releaseAdded),{cwd}),true);
 assert.equal(apkFormalReleaseRequested('push',push(unrelated,releaseAdded),{cwd}),true,'explicit final-release marker authorizes publication');
 writeFileSync(join(cwd,dir,'20261111-reviewed-final-release.txt'),'corrected formal release');
 const releaseModified=commit();
 assert.equal(apkFormalReleaseRequested('push',push(releaseAdded,releaseModified),{cwd}),true,'editing a formal release marker remains explicit');
 writeFileSync(join(cwd,'ordinary-2.txt'),'ordinary source edit');
 const afterRelease=commit();
 assert.equal(apkBuildRequested('push',push(releaseModified,afterRelease),{cwd}),false);
 assert.equal(apkFormalReleaseRequested('push',push(releaseModified,afterRelease),{cwd}),false);
 const pr={repository:{full_name:'synthetic/repo'},pull_request:{base:{sha:archived},head:{sha:unrelated,repo:{full_name:'synthetic/repo'}}}};
 assert.equal(apkBuildRequested('pull_request',pr,{cwd}),true);
 assert.equal(apkFormalReleaseRequested('pull_request',pr,{cwd}),false,'QA-only PR must not authorize formal release');
 const releasePr={repository:{full_name:'synthetic/repo'},pull_request:{base:{sha:unrelated},head:{sha:releaseAdded,repo:{full_name:'synthetic/repo'}}}};
 assert.equal(apkFormalReleaseRequested('pull_request',releasePr,{cwd}),true,'formal release marker remains explicit through PR review');
 assert.equal(apkBuildRequested('pull_request',{...pr,pull_request:{...pr.pull_request,base:{sha:base},head:{sha:archived,repo:{full_name:'synthetic/repo'}}}},{cwd}),false,'stale PR must not revive archived markers');
 assert.equal(apkBuildRequested('pull_request',{...pr,pull_request:{...pr.pull_request,head:{...pr.pull_request.head,repo:{full_name:'synthetic/fork'}}}},{cwd}),false);
 assert.equal(apkBuildRequested('push',{...push(base,qaAdded),ref:'refs/heads/feature'},{cwd}),false);
 assert.equal(apkBuildRequested('push',{...push(base,qaAdded),deleted:true},{cwd}),false);
 assert.deepEqual(apkBuildRequest('workflow_dispatch',{}, {cwd}),{requested:true,releaseRequested:false});
 assert.equal(apkBuildRequested('schedule',{}, {cwd}),false);
 assert.throws(()=>apkBuildRequested('push',push('invalid',qaAdded),{cwd}));
 assert.throws(()=>apkBuildRequested('push',push('f'.repeat(40),qaAdded),{cwd}),'unknown Git range fails closed');
 const eventPath=join(cwd,'event.json'),outputPath=join(cwd,'output.txt');
 writeFileSync(eventPath,JSON.stringify(push(archived,qaAdded)));
 const cli=spawnSync(process.execPath,[gateUrl.pathname],{cwd,encoding:'utf8',env:{...process.env,GITHUB_EVENT_NAME:'push',GITHUB_EVENT_PATH:eventPath,GITHUB_OUTPUT:outputPath}});
 assert.equal(cli.status,0,cli.stderr);
 assert.equal(readFileSync(outputPath,'utf8'),'requested=true\nrelease_requested=false\n');
 console.log('APK request gate: QA vs formal release classification, archive/delete, PR range, fork, manual recovery and fail-closed Git/CLI checks passed');
}finally{rmSync(cwd,{recursive:true,force:true});}