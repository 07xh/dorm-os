import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';

const code=readFileSync(new URL('../public/xiaoxu-task-import.js',import.meta.url),'utf8');
const context={Date};
runInNewContext(code,context);
const api=context.XiaoxuTaskImport;
assert.equal(api.FORMAT,'xiaoxu-task-batch-v1');
const batch=(tasks,source='chaoxing')=>({format:api.FORMAT,source,tasks});
const item=(externalId,title,status='todo',due='2026-11-20')=>({externalId,title,course:'高等数学',due,status});
const clean=api.normalizeBatch(batch([item('course-1/work-9','微积分作业')]));
assert.equal(clean.tasks[0].title,'微积分作业');
assert.throws(()=>api.normalizeBatch(batch([item('id','任务','todo','2026-02-30')])),/日期/);
assert.throws(()=>api.normalizeBatch(batch([item('id','任务','done')])),/状态/);
assert.throws(()=>api.normalizeBatch(batch([item('id','A'),item('id','B')])),/重复 ID/);
assert.throws(()=>api.normalizeBatch({format:api.FORMAT,source:'untrusted',tasks:[]}),/来源/);
assert.throws(()=>api.normalizeBatch(batch([{externalId:'e',title:'',status:'todo'}])),/任务/);
assert.throws(()=>api.normalizeBatch(batch([{...item('id','ok'),title:'t'.repeat(101)}])),/超长/);
assert.throws(()=>api.normalizeBatch({format:api.FORMAT,source:'chaoxing',tasks:[...Array(301)].map((_,i)=>item(String(i),'a'))}),/300/);
let count=0;const id=()=>`new-${++count}`;const now='2026-11-02T14:00:00.000Z';
const legacy={id:'local-1',title:'已经自己完成的 Python 练习',category:'Python',done:true,due:'2026-11-01'};
const initial=api.planImport([legacy],batch([item('work-1','微积分作业')]),id,now);
assert.equal(initial.added,1);
assert.equal(initial.updated,0);
assert.equal(initial.tasks.length,2);
assert.equal(initial.tasks[0].done,true);
assert.equal(initial.tasks[1].source,'chaoxing');
assert.equal(initial.tasks[1].sourceStatus,'todo');
const existing=[...initial.tasks.slice(0,1),{...initial.tasks[1],done:true,category:'高数'}];
const second=api.planImport(existing,batch([item('work-1','微积分作业修改','submitted','2026-11-23')]),id,now);
assert.equal(second.added,0);
assert.equal(second.updated,1);
assert.equal(second.tasks.length,2);
assert.equal(second.tasks[1].sourceStatus,'submitted');
assert.equal(second.tasks[1].category,'高数','local categorization is preserved');
assert.equal(second.tasks[1].done,true,'local completion is not overwritten by platform status');
assert.equal(existing[1].title,'微积分作业','source input is not mutated');
const repeat=api.planImport(second.tasks,batch([item('work-1','微积分作业修改','submitted','2026-11-23')]),id,now);
assert.equal(repeat.updated,0);
assert.equal(repeat.unchanged,1);
assert.equal(repeat.tasks.length,2,'repeat imports do not duplicate');
const otherSource=api.planImport(repeat.tasks,batch([item('work-1','二课活动','unknown','')],'second_class'),id,now);
assert.equal(otherSource.added,1,'same external ID from different sources is distinct');
const missing=api.planImport(otherSource.tasks,batch([]),id,now);
assert.equal(missing.tasks.length,3,'missing source items never delete cached tasks');
const full=Array.from({length:300},(_,i)=>({id:'task-'+i,title:'item-'+i,source:'manual'}));
assert.throws(()=>api.planImport(full,batch([item('new-external','new')]),id,now),/300/);
assert.equal(full.length,300,'capacity failure is atomic');
assert.throws(()=>api.planImport([],batch([item('valid','A'),item('valid','B')]),id,now),/重复/);
console.log('校序任务快照：严格校验、不同来源去重、差异更新、本地勾选保留、缺项保护、容量原子回退均通过');
